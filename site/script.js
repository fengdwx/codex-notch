const STORAGE_KEY = "codexnotch-lang";
const OTHER_LABEL = { en: "中文", zh: "EN" };
const heroVideo = document.querySelector("[data-hero-video]");

const resolveInitialLang = () => {
  const params = new URLSearchParams(location.search);
  const fromQuery = params.get("lang");
  if (fromQuery === "en" || fromQuery === "zh") return fromQuery;
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "en" || stored === "zh") return stored;
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
};

const applyLang = (lang) => {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value == null) return;
    if (el.tagName === "META") el.setAttribute("content", value);
    else if (el.tagName === "TITLE") document.title = value;
    else el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const value = dict[el.dataset.i18nHtml];
    if (value != null) el.innerHTML = value;
  });

  if (heroVideo) {
    const src = `assets/codex-notch-demo-${lang}.mp4`;
    if (!heroVideo.currentSrc.endsWith(src)) {
      heroVideo.querySelector("source").src = src;
      heroVideo.load();
      heroVideo.play().catch(() => {});
    }
  }

  const label = document.querySelector("[data-lang-label]");
  if (label) label.textContent = OTHER_LABEL[lang];
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (_) {}
};

let currentLang = resolveInitialLang();
applyLang(currentLang);

document.querySelector("[data-lang-toggle]")?.addEventListener("click", () => {
  currentLang = currentLang === "en" ? "zh" : "en";
  applyLang(currentLang);
});

const header = document.querySelector("[data-header]");
const menuToggle = document.querySelector("[data-menu-toggle]");
const nav = document.querySelector("[data-nav]");

const playHeroVideo = () => {
  if (!heroVideo || document.hidden) return;
  heroVideo.play().catch(() => {});
};
playHeroVideo();
heroVideo?.addEventListener("canplay", playHeroVideo);
document.addEventListener("visibilitychange", playHeroVideo);

const updateHeader = () => header?.classList.toggle("is-scrolled", window.scrollY > 20);
updateHeader();
window.addEventListener("scroll", updateHeader, { passive: true });

menuToggle?.addEventListener("click", () => {
  const isOpen = nav?.classList.toggle("is-open") ?? false;
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});
nav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("is-open");
    menuToggle?.setAttribute("aria-expanded", "false");
  });
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);
document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));
